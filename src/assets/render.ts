import type { AssetModel, GapAction, ModelAsset, ModelType } from "./model.ts";

/**
 * Dateien des Asset-Exports. Die Dokumente sind englisch, weil sie fuer die Weitergabe an eine Plattform-Entwicklung
 * gedacht sind; die Oberflaeche der Werkstatt bleibt deutsch.
 */

export interface AssetFile {
  readonly path: string;
  readonly text: string;
}

const ACTION_LABEL: Readonly<Record<GapAction, string>> = {
  "extend-model": "Extend the asset model",
  generated: "Covered by a generated type",
  review: "Review in the workshop",
  info: "Note",
};

const ORIGIN_LABEL = (type: ModelType): string => (type.origin === "generated" ? "generated by the export" : type.extended ? "target profile, extended" : "target profile");

/** Tabellenzelle ohne Zeilenumbruch und senkrechten Strich. */
const cell = (text: string): string => text.replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();

function valueMap(map: Readonly<Record<string, string>> | undefined): string {
  if (!map) return "";
  const entries = Object.entries(map);
  const shown = entries.slice(0, 4).map(([key, value]) => `${key}=${value}`).join(", ");
  return entries.length > 4 ? `${shown}, … (${entries.length})` : shown;
}

export function templateLibraryMarkdown(model: AssetModel): string {
  const lines = [
    "# Asset template library",
    "",
    `Generated by ${model.generator} with target profile "${model.profile}".`,
    "",
    `${model.stats.typesFromProfile} types from the target profile (${model.stats.typesExtended} of them extended), ${model.stats.typesGenerated} generated by the export, ${model.stats.equipment} equipment assets in ${model.stats.spaces} spaces, ${model.stats.bindings} attribute bindings on ${model.stats.groupAddresses} group addresses.`,
    "",
    "| Type | Class | Origin | Assets | Attributes |",
    "|---|---|---|---|---|",
    ...model.types.map((type) => `| \`${type.key}\` | ${cell(type.class)} | ${ORIGIN_LABEL(type)} | ${type.assets} | ${type.attributes.length} |`),
  ];
  for (const type of model.types) {
    lines.push("", `## ${type.key}`, "", `Class \`${type.class}\`, ${ORIGIN_LABEL(type)}, ${type.assets} asset${type.assets === 1 ? "" : "s"}.`);
    if (type.tags.length > 0) lines.push("", `Tags: ${type.tags.map((tag) => `\`${tag}\``).join(", ")}`);
    if (type.attributes.length === 0) {
      lines.push("", "No attributes.");
      continue;
    }
    lines.push("", "| Subtype | Attribute | Unit | DPT | Values | Origin |", "|---|---|---|---|---|---|");
    for (const attribute of type.attributes) {
      lines.push(
        `| ${attribute.subtype} | \`${attribute.name}\` | ${cell(attribute.unit ?? "")} | ${attribute.dpt ?? ""} | ${cell(valueMap(attribute.map))} | ${attribute.origin === "profile" ? "profile" : attribute.origin === "extension" ? "**extension**" : "generated"} |`,
      );
    }
  }
  return `${lines.join("\n")}\n`;
}

export function gapsMarkdown(model: AssetModel): string {
  const lines = [
    "# Where the asset model does not fit KNX",
    "",
    `Generated by ${model.generator} with target profile "${model.profile}". Each entry names a KNX concept that the asset model cannot express as it is, how often it occurs in this project, and what the export did instead.`,
    "",
    "| # | Gap | Action | Count |",
    "|---|---|---|---|",
    ...model.gaps.map((gap, index) => `| ${index + 1} | ${cell(gap.title)} | ${ACTION_LABEL[gap.action]} | ${gap.count} |`),
  ];
  model.gaps.forEach((gap, index) => {
    lines.push("", `## ${index + 1}. ${gap.title}`, "", `*${ACTION_LABEL[gap.action]}* · id \`${gap.id}\` · ${gap.count} occurrence${gap.count === 1 ? "" : "s"}`, "", gap.detail);
    if (gap.examples.length > 0) lines.push("", "Examples:", "", ...gap.examples.map((example) => `- ${example}`));
  });
  return `${lines.join("\n")}\n`;
}

export type TreeKind = "location" | "function";

/** Kinder je Eltern-Asset in einem der beiden Baeume, in der Reihenfolge des Modells. */
export function treeChildren(model: AssetModel, tree: TreeKind): Map<string | null, ModelAsset[]> {
  const children = new Map<string | null, ModelAsset[]>();
  for (const asset of model.assets) {
    // Im Funktionsbaum stehen nur Assets, die dort einen Platz haben: Systeme und alles, was unter einem haengt.
    if (tree === "function" && asset.parent.function === null && asset.kind !== "system") continue;
    const key = tree === "location" ? asset.parent.location : asset.parent.function;
    const list = children.get(key);
    if (list) list.push(asset);
    else children.set(key, [asset]);
  }
  return children;
}

function treeMarkdown(model: AssetModel, tree: TreeKind): string {
  const children = treeChildren(model, tree);
  const lines =
    tree === "location"
      ? ["# Location tree", "", "Where is it? Asset name, type and code. Equipment lists its bound attributes.", ""]
      : ["# Functional tree", "", "What does it belong to? Systems per trade and building, central functions, and the assets they control.", ""];
  const walk = (parent: string | null, depth: number): void => {
    for (const asset of children.get(parent) ?? []) {
      const attributes = asset.bindings.length > 0 ? ` · ${asset.bindings.map((binding) => binding.attribute).join(", ")}` : "";
      lines.push(`${"  ".repeat(depth)}- **${cell(asset.name)}** \`${asset.type}\` ${asset.code}${attributes}`);
      if (depth < 20) walk(asset.id, depth + 1);
    }
  };
  walk(null, 0);
  return `${lines.join("\n")}\n`;
}

export function locationTreeMarkdown(model: AssetModel): string {
  return treeMarkdown(model, "location");
}

export function functionTreeMarkdown(model: AssetModel): string {
  return treeMarkdown(model, "function");
}

const csvCell = (value: string | undefined): string => {
  const text = value ?? "";
  // Names come from the project; a leading formula character must not run when the file is opened in a spreadsheet.
  const safe = /^[=+\-@\t\r]/.test(text) ? `'${text}` : text;
  return /[",\n\r]/.test(safe) ? `"${safe.replace(/"/g, '""')}"` : safe;
};

/** One row per binding: the field-side key (group address) to (asset, subtype, attribute). */
export function datapointsCsv(model: AssetModel): string {
  const header = ["asset_code", "asset_name", "asset_type", "subtype", "attribute", "dpt", "write_ga", "feedback_ga", "readable", "role", "ga_names"];
  const rows = model.assets.flatMap((asset) =>
    asset.bindings.map((binding) =>
      [asset.code, asset.name, asset.type, binding.subtype, binding.attribute, binding.dpt, binding.write, binding.feedback, binding.readable === undefined ? "" : String(binding.readable), binding.role, binding.gaNames.join(" | ")].map(csvCell).join(","),
    ),
  );
  return `${[header.join(","), ...rows].join("\n")}\n`;
}

/** reviewList: the review checklist built from the full model, so rejected assets stay on record. */
export function assetFiles(model: AssetModel, mappingPrompt: string | undefined, reviewList?: string): AssetFile[] {
  return [
    { path: "asset-model.json", text: `${JSON.stringify(model, null, 2)}\n` },
    { path: "template-library.md", text: templateLibraryMarkdown(model) },
    { path: "gaps.md", text: gapsMarkdown(model) },
    { path: "location-tree.md", text: locationTreeMarkdown(model) },
    { path: "function-tree.md", text: functionTreeMarkdown(model) },
    { path: "datapoints.csv", text: datapointsCsv(model) },
    ...(reviewList ? [{ path: "review.csv", text: reviewList }] : []),
    ...(mappingPrompt ? [{ path: "mapping-prompt.md", text: mappingPrompt }] : []),
  ];
}
